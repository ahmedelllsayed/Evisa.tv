export type MessageKey = keyof typeof en;

export function isArabicLocale(locale: string) {
  return locale.toLowerCase().startsWith("ar");
}

export function t(locale: string, key: MessageKey) {
  return (isArabicLocale(locale) ? ar : en)[key];
}

export function tf(locale: string, key: MessageKey, vars: Record<string, string | number>) {
  return t(locale, key).replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}
